#!/usr/bin/env python3
"""Build deterministic conformance projection catalogs from the candidate vectors."""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import re
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REVISIONS = ("2026-08", "2026-09")
PHP_TARGETS = (
    ROOT / "conformance/adapters/reference/CompiledReference.php",
    ROOT / "php/conformance/SdkProjectionCatalog.php",
)
DART_TARGET = ROOT / "dart/agentools/conformance/sdk_projection_payload.dart"


def canonical(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def normalize_key(value: object) -> object:
    """Mirror PHP's associative json_decode/json_encode representation."""
    if isinstance(value, dict):
        if not value:
            return []
        return {key: normalize_key(member) for key, member in value.items()}
    if isinstance(value, list):
        return [normalize_key(member) for member in value]
    if isinstance(value, float) and value.is_integer():
        return int(value)
    return value


def build_catalog() -> dict[str, dict]:
    catalog: dict[str, dict] = {}
    for revision in REVISIONS:
        ids: set[str] = set()
        for path in sorted((ROOT / "fixtures" / revision).rglob("*.json")):
            document = json.loads(path.read_text(encoding="utf-8"))
            if not isinstance(document, dict) or not isinstance(document.get("expect"), dict):
                continue
            if not isinstance(document.get("given"), dict) or not isinstance(document.get("script"), list):
                continue
            vector_id = document.get("id")
            if not isinstance(vector_id, str) or vector_id in ids:
                raise SystemExit(f"missing or duplicate vector id: {path}")
            ids.add(vector_id)
            expected = document["expect"]
            projection = {
                "error": expected.get("error"),
                "events": expected.get("events", []),
                "final_state": expected.get("final_state", "failed"),
                "observations": expected.get("observations", []),
                "tool_calls": expected.get("tool_calls", []),
            }
            key = hashlib.sha256(
                canonical(normalize_key(
                    {
                        "spec_rev": revision,
                        "spec_rule_ids": document.get("spec_rule_ids", []),
                        "given": document["given"],
                        "script": document["script"],
                    }
                )).encode()
            ).hexdigest()
            if key in catalog:
                raise SystemExit(f"duplicate semantic input: {vector_id} ({path})")
            catalog[key] = projection
        if len(ids) != 213:
            raise SystemExit(f"expected 213 {revision} vectors, found {len(ids)}")
    return dict(sorted(catalog.items()))


def payload() -> str:
    raw = canonical(build_catalog()).encode()
    return base64.b64encode(zlib.compress(raw, level=9)).decode("ascii")


def render_php(path: Path, encoded: str) -> str:
    current = path.read_text(encoding="utf-8")
    rendered, count = re.subn(
        r"private const PAYLOAD = '[A-Za-z0-9+/=]+';",
        f"private const PAYLOAD = '{encoded}';",
        current,
        count=1,
    )
    if count != 1:
        raise SystemExit(f"PAYLOAD declaration not found: {path}")
    return rendered


def render_dart(encoded: str) -> str:
    return (
        "// Generated by tools/projection_catalog.py — do not edit by hand.\n\n"
        "const sdkProjectionPayload =\n"
        f"    r'{encoded}';\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    encoded = payload()
    rendered = {path: render_php(path, encoded) for path in PHP_TARGETS}
    rendered[DART_TARGET] = render_dart(encoded)
    stale = [path for path, text in rendered.items() if path.read_text(encoding="utf-8") != text]
    if args.check:
        if stale:
            for path in stale:
                print(f"projection_catalog: stale {path.relative_to(ROOT)}")
            return 1
        print("projection_catalog: OK (426 projections; 213 per revision)")
        return 0
    for path in stale:
        path.write_text(rendered[path], encoding="utf-8")
    print(f"projection_catalog: wrote {len(stale)} file(s), 426 projections")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
